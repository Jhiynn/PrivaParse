"""Compile the annotated gold source into JSONL with character offsets.

Hand-counted offsets are wrong offsets. The canonical artefact is
``gold/de_gold_source.md``, where entities are marked inline::

    Sehr geehrter Herr {{PERSON:Dr. Max Mustermann}},

This script strips the markers, computes the offsets, and verifies that every
emitted span actually slices back to its own text. The output format is
deliberately the one ``GLiNER2Trainer`` reads, so the same file becomes training
data in Phase 2 without conversion.

Run with::

    python -m privaparse.evaluation.build_gold
"""

from __future__ import annotations

import argparse
import itertools
import json
import random
import re
import string
import sys
from dataclasses import dataclass
from pathlib import Path

from privaparse.evaluation import DEFAULT_GOLD_PATH, DEFAULT_GOLD_SOURCE

DEFAULT_SOURCE = DEFAULT_GOLD_SOURCE
DEFAULT_TARGET = DEFAULT_GOLD_PATH

_HEADER_RE = re.compile(r"^###\s+id:\s*(?P<id>\S+)\s*(?:\|\s*kind:\s*(?P<kind>\S+))?\s*$")
#: Type names match the same shape the catalogue itself enforces
#: (``TYPE_NAME_RE`` in database/placeholder.py) rather than one fixed
#: alternation, so widening VALID_TYPES below is the only edit a new
#: annotated type ever needs here.
_MARKER_RE = re.compile(r"\{\{(?P<type>[A-Z][A-Z0-9_]*):(?P<text>[^{}]+)\}\}")

#: Types the annotated source actually uses. An explicit allowlist, not "every
#: name the catalogue knows" — a typo in the source (`{{ADRESS:...}}`) must
#: fail loudly here, at build time, rather than compiling into a gold entity
#: that only test_every_gold_type_exists_in_the_catalogue would later catch.
VALID_TYPES = {
    "PERSON", "EMAIL", "PHONE",
    # Batch A — decidable types, generated by generate_decidable().
    "IBAN", "CARD", "TAX_ID", "IP", "POSTAL_CODE",
    # Batch B — fuzzy types, hand-annotated.
    "ADDRESS", "DATE_OF_BIRTH", "NATIONAL_ID", "PASSPORT", "ACCOUNT_ID", "USERNAME",
    # Batch D (Task 13) — decidable types, generated by generate_decidable().
    "ROUTING_NUMBER", "CARD_EXPIRY", "CARD_CVV", "ACCOUNT_NUMBER",
    # Batch E (Task 13) — fuzzy types, hand-annotated. Four of these ship
    # disabled (CITY, REGION, COUNTRY, DATE); they are still annotated here —
    # gold data records what a type would need to get right, not whether the
    # catalogue currently sends its labels to the model.
    "CITY", "REGION", "COUNTRY", "DRIVERS_LICENSE", "LICENSE_NUMBER", "SECRET", "DATE",
}


@dataclass
class Document:
    id: str
    kind: str
    text: str
    entities: list[dict]

    def to_json(self) -> dict:
        return {
            "id": self.id,
            "kind": self.kind,
            "text": self.text,
            "entities": self.entities,
        }


def parse_source(source: str) -> list[Document]:
    documents: list[Document] = []
    current_id: str | None = None
    current_kind = "unspecified"
    buffer: list[str] = []

    def flush() -> None:
        if current_id is None:
            return
        raw = "".join(buffer).strip("\n")
        if not raw:
            raise ValueError(f"document {current_id} is empty")
        documents.append(_compile_document(current_id, current_kind, raw))

    for line in source.splitlines(keepends=True):
        header = _HEADER_RE.match(line.rstrip("\n"))
        if header:
            flush()
            current_id = header.group("id")
            current_kind = header.group("kind") or "unspecified"
            buffer = []
            continue
        if current_id is not None:
            buffer.append(line)

    flush()
    return documents


def _compile_document(doc_id: str, kind: str, annotated: str) -> Document:
    text_parts: list[str] = []
    entities: list[dict] = []
    cursor = 0
    plain_length = 0

    for match in _MARKER_RE.finditer(annotated):
        before = annotated[cursor : match.start()]
        text_parts.append(before)
        plain_length += len(before)

        surface = match.group("text")
        entities.append(
            {
                "start": plain_length,
                "end": plain_length + len(surface),
                "type": match.group("type"),
                "text": surface,
            }
        )
        text_parts.append(surface)
        plain_length += len(surface)
        cursor = match.end()

    text_parts.append(annotated[cursor:])
    text = "".join(text_parts)

    _validate(doc_id, text, entities)
    return Document(id=doc_id, kind=kind, text=text, entities=entities)


def _validate(doc_id: str, text: str, entities: list[dict]) -> None:
    if "{{" in text or "}}" in text:
        raise ValueError(f"{doc_id}: unparsed marker braces left in the text")

    for entity in entities:
        sliced = text[entity["start"] : entity["end"]]
        if sliced != entity["text"]:
            raise ValueError(
                f"{doc_id}: offset mismatch — text[{entity['start']}:{entity['end']}] "
                f"is {sliced!r}, expected {entity['text']!r}"
            )
        if entity["type"] not in VALID_TYPES:
            raise ValueError(f"{doc_id}: unknown placeholder type {entity['type']!r}")

    ordered = sorted(entities, key=lambda e: e["start"])
    for left, right in itertools.pairwise(ordered):
        if left["end"] > right["start"]:
            raise ValueError(f"{doc_id}: overlapping annotations at {left['start']}")


def write_jsonl(documents: list[Document], target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="\n") as handle:
        for document in documents:
            handle.write(json.dumps(document.to_json(), ensure_ascii=False) + "\n")


def load_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _iban_de(account: int, blz: int = 37040044) -> str:
    """A syntactically real German IBAN with correct check digits.

    Generated rather than hand-written because a gold set full of IBANs that
    fail their own checksum would measure the pattern, not the validator.
    """
    body = f"{blz:08d}{account:010d}"
    rearranged = body + "1314" + "00"  # DE -> 1314, placeholder check digits
    check = 98 - int(rearranged) % 97
    return f"DE{check:02d}{body}"


def _luhn_complete(prefix: str, length: int) -> str:
    partial = prefix.ljust(length - 1, "0")
    total = 0
    for index, character in enumerate(reversed(partial + "0")):
        digit = int(character)
        if index % 2 == 1:
            digit *= 2
            if digit > 9:
                digit -= 9
        total += digit
    return partial + str((10 - total % 10) % 10)


def _tax_id_de(base: str) -> str:
    """Complete a ten-digit stem with its ISO 7064 MOD 11,10 check digit."""
    remainder = 10
    for character in base:
        total = (int(character) + remainder) % 10 or 10
        remainder = (2 * total) % 11
    return base + str((11 - remainder) % 10)


def _bic_de(rng: random.Random, *, branch: bool) -> str:
    """A syntactically valid BIC: 4-letter bank code, "DE", 2-character
    alphanumeric location, and — when ``branch`` is set — a 3-character
    alphanumeric branch suffix.

    A BIC has no public checksum; ``_BIC_RE`` in validators.py is a shape
    check, not an algorithm with a digit to get right. "By construction"
    means matching that shape, the same sense POSTAL_CODE's generation below
    already uses for a validator that is shape-only too.
    """
    letters = string.ascii_uppercase
    location_alphabet = letters + string.digits
    bank_code = "".join(rng.choice(letters) for _ in range(4))
    location_code = "".join(rng.choice(location_alphabet) for _ in range(2))
    bic = f"{bank_code}DE{location_code}"
    if branch:
        bic += "".join(rng.choice(location_alphabet) for _ in range(3))
    return bic


def generate_decidable(seed: int = 1) -> list[tuple[str, str, str | None]]:
    """(placeholder type, value, validator name) for the checksum-backed types.

    Every value is generated to satisfy its own validator, so the gold set
    exercises the checksum rather than accidentally testing that a wrong number
    is rejected. ACCOUNT_NUMBER is the one entry with no validator to satisfy:
    entities.default.yaml declares none for it, because an 8-10 digit German
    Kontonummer has no single, nationwide check-digit scheme the way an IBAN
    or a Steuer-ID does — the reason IBAN replaced it. Its slot is ``None``,
    and "by construction" for it means only that same 8-10 digit length
    range, not a checksum that does not exist to satisfy.
    """
    rng = random.Random(seed)  # noqa: S311 -- synthetic gold data, nothing cryptographic
    out: list[tuple[str, str, str | None]] = []
    for _ in range(6):
        out.append(("IBAN", _iban_de(rng.randrange(10**9)), "iban_mod97"))
    for prefix in ("4", "51", "37"):
        out.append(("CARD", _luhn_complete(prefix + str(rng.randrange(10**8)), 16), "luhn"))
    for _ in range(4):
        out.append(("TAX_ID", _tax_id_de(f"{rng.randrange(10**9):010d}"), "tax_de"))
    for _ in range(3):
        out.append(("IP", (f"{rng.randrange(1,224)}.{rng.randrange(256)}."
                            f"{rng.randrange(256)}.{rng.randrange(1,255)}"), "ip_parse"))
    for _ in range(3):
        out.append(("POSTAL_CODE", f"{rng.randrange(10000, 100000)}", "postal_de"))
    # Batch D (Task 13) — the four types generate_decidable() did not yet cover.
    out.append(("ROUTING_NUMBER", f"{rng.randrange(10**8):08d}", "bank_routing_de"))
    out.append(("ROUTING_NUMBER", _bic_de(rng, branch=False), "bank_routing_de"))
    out.append(("ROUTING_NUMBER", _bic_de(rng, branch=True), "bank_routing_de"))
    for year_width in (2, 4, 2):  # both MM/YY and MM/YYYY
        month = rng.randrange(1, 13)
        # expiry_shape has no notion of "plausible year" — any 2- or 4-digit
        # run satisfies it — but a card that expires in the year 3782 reads
        # as a typo, not a gold example, in the sentence it gets embedded in.
        # Constraining to a near-future window keeps the value realistic
        # without weakening what the validator is actually being asked to
        # check (its shape, not the calendar).
        full_year = 2026 + rng.randrange(1, 9)
        year = full_year if year_width == 4 else full_year % 100
        out.append(("CARD_EXPIRY", f"{month:02d}/{year:0{year_width}d}", "expiry_shape"))
    for length in (3, 4, 3):  # both 3- and 4-digit CVVs
        out.append(("CARD_CVV", f"{rng.randrange(10**length):0{length}d}", "cvv_shape"))
    for length in (8, 9, 10):
        out.append(("ACCOUNT_NUMBER", f"{rng.randrange(10**length):0{length}d}", None))
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    args = parser.parse_args(argv)

    documents = parse_source(args.source.read_text(encoding="utf-8"))
    if not documents:
        print(f"no documents found in {args.source}", file=sys.stderr)
        return 1

    write_jsonl(documents, args.target)

    counts: dict[str, int] = {}
    for document in documents:
        for entity in document.entities:
            counts[entity["type"]] = counts.get(entity["type"], 0) + 1

    empty = sum(1 for d in documents if not d.entities)
    print(f"wrote {len(documents)} document(s) to {args.target}")
    for entity_type, count in sorted(counts.items()):
        print(f"  {entity_type:<7} {count}")
    print(f"  {'(none)':<7} {empty} document(s) with no entities at all")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
